// Generates what arboretum knows of the engine from the komorebi in this repository, the folder above:
// `node scripts/engine.mjs` (npm test, npm run typecheck and the dev mode run it first). Arboretum ships as part of
// komorebi, so it always runs the engine beside it; nothing is pinned. Outputs, all gitignored:
//   src/generated/engine.ts       the commit (HEAD), param types, the editor's slider ranges and select choices, legacy
//                                 keys, look names, experimental look names
//   src/generated/builtins.ts     DEFAULTS' values and every shipped look as the module holds it, so a look that is an
//                                 unchanged built-in can be recognised and refused (builtinTwin in validate.ts)
//   test/fixtures/looks.json      every shipped look, the validator's golden fixtures
//   test/fixtures/lineage.json    the built-in looks as the lineage page reads them, for its tests
//   public/engine/*               the browser bundle (every camera, every feature tier) and the lineage page's built-in looks,
//                                 each named by its content, + engine.json naming both
// Everything is built into a temporary place first and only put where it is read once every step has succeeded
// (scripts/stage.mjs), so a failed run leaves the last good outputs exactly as they were.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { inputKeys, rowsOf } from './editor-rows.mjs';
import { install } from './stage.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KOMOREBI = join(ROOT, '..');

const commit = execFileSync('git', ['-C', KOMOREBI, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const readdirSyncOr = (dir) => { try { return readdirSync(dir); } catch { return []; } };
const komorebi = (file) => import(pathToFileURL(join(KOMOREBI, file)).href);

const tmp = mkdtempSync(join(tmpdir(), 'arboretum-engine-'));
try {
  const { DEFAULTS, LEGACY_KEYS, PARAMS } = await komorebi('engine/komorebi-params.js');
  const { PRESETS, EXPERIMENTAL, PLAYLISTS } = await komorebi('presets.js');
  const { PRESENTATION_PROFILES, FIDELITY_KEYS, PLAYBACK_KEYS } = await komorebi('engine/komorebi-session.js');
  // Every look name keeps every camera, and `all` keeps every fall tier. Built into tmp, so komorebi's dist/ is left alone.
  const { build } = await komorebi('embed-build.mjs');

  const types = Object.entries(DEFAULTS).map(([k, v]) => {
    if (!['number', 'boolean', 'string'].includes(typeof v)) throw new Error(`DEFAULTS.${k} is a ${typeof v}`);
    return [k, typeof v];
  });

  // The editor's own knobs are the bound on a look (brief 07): each parameter's row in komorebi's registry, PARAMS.
  const rows = rowsOf(PARAMS);
  const editorKeys = inputKeys(PARAMS); // the editor's inputs a look carries (time_of_day, latitude); DEFAULTS has no entry for them
  const ranges = new Map();
  const choices = new Map();
  for (const row of rows) {
    const type = editorKeys.includes(row.key) ? 'number' : typeof DEFAULTS[row.key];
    if (row.kind === 's') {
      if (type !== 'number') throw new Error(`editor slider ${row.key} is for a ${type} param`);
      if (ranges.has(row.key)) throw new Error(`editor has two sliders for ${row.key}`);
      ranges.set(row.key, row);
    } else {
      if (type !== (row.kind === 'sel' ? 'number' : 'string')) throw new Error(`editor ${row.kind} ${row.key} is for a ${type} param`);
      if (choices.has(row.key)) throw new Error(`editor has two selects for ${row.key}`);
      choices.set(row.key, row.choices);
    }
  }
  const isAngle = (r) => r.key.endsWith('_deg') && ((r.min === -180 && r.max === 180) || (r.min === 0 && r.max === 360));
  const angleKeys = [...ranges.values()].filter(isAngle).map((r) => r.key);
  const integerKeys = [...ranges.values()].filter((r) => r.step === 1).map((r) => r.key);
  const entry = ([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`;
  const stage = join(tmp, 'arboretum-stage');
  mkdirSync(stage);
  writeFileSync(join(stage, 'engine.ts'), [
    '// Generated by scripts/engine.mjs from the komorebi beside arboretum. Do not edit by hand.',
    `export const ENGINE_COMMIT = ${JSON.stringify(commit)};`,
    `export const PRESENTATION_IDS: string[] = ${JSON.stringify(Object.keys(PRESENTATION_PROFILES))};`,
    `export const FIDELITY_KEYS: string[] = ${JSON.stringify(FIDELITY_KEYS)};`,
    `export const PLAYBACK_KEYS: string[] = ${JSON.stringify(PLAYBACK_KEYS)};`,
    '',
    'export const PARAM_TYPES: Record<string, \'number\' | \'boolean\' | \'string\'> = {',
    ...types.map(entry),
    '};',
    '',
    '// The komorebi editor\'s slider ranges, exactly as its panel has them (validate.ts adds the leeway).',
    'export const PARAM_RANGES: Record<string, { min: number; max: number }> = {',
    ...[...ranges.values()].map((r) => `  ${JSON.stringify(r.key)}: { "min": ${r.min}, "max": ${r.max} },`),
    '};',
    '',
    '// Sliders whose step is 1: their stretched bounds round to whole numbers.',
    `export const INTEGER_KEYS: string[] = ${JSON.stringify(integerKeys)};`,
    '',
    '// Sliders that are a direction around a circle (-180...180 or 0...360, named *_deg): any number is one.',
    `export const ANGLE_KEYS: string[] = ${JSON.stringify(angleKeys)};`,
    '',
    '// The editor\'s selects: the only values a look may hold for these keys.',
    'export const PARAM_CHOICES: Record<string, (number | string)[]> = {',
    ...[...choices].map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
    '};',
    '',
    '// Old spelling -> current name.',
    'export const LEGACY_KEYS: Record<string, string> = {',
    ...Object.entries(LEGACY_KEYS).map(entry),
    '};',
    '',
    '// Every shipped look, so a `look:<name>` parent can be checked.',
    `export const LOOK_NAMES: string[] = ${JSON.stringify(Object.keys(PRESETS))};`,
    '',
    `export const EXPERIMENTAL_LOOKS: string[] = ${JSON.stringify(EXPERIMENTAL)};`,
    '',
  ].join('\n'));

  const lookBlock = (rec) => Object.entries(rec).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  writeFileSync(join(stage, 'builtins.ts'), [
    '// Generated by scripts/engine.mjs from the komorebi beside arboretum. Do not edit by hand.',
    '',
    '// Every key of the engine\'s DEFAULTS and its value: what a look that leaves a key out takes.',
    'export const DEFAULT_VALUES: Record<string, number | boolean | string> = {',
    ...lookBlock(DEFAULTS),
    '};',
    '',
    '// Every shipped look, name -> params, exactly as presets.js holds them.',
    'export const BUILTIN_LOOKS: Record<string, Record<string, number | boolean | string>> = {',
    ...Object.entries(PRESETS).flatMap(([name, look]) => [`  ${JSON.stringify(name)}: {`, ...lookBlock(look).map((l) => `  ${l}`), '  },']),
    '};',
    '',
  ].join('\n'));

  writeFileSync(join(stage, 'looks.json'), JSON.stringify(PRESETS, null, 2) + '\n');

  // What the lineage page (public/js/lineage-infer.js) knows of the built-in looks: each one's params, the comment written
  // directly above it in presets.js (which often names the look it was made from), and when git first saw its name as a
  // key, in presets.js or in komorebi.js where the looks lived before; plus the tables two looks are compared by.
  const presetsLines = readFileSync(join(KOMOREBI, 'presets.js'), 'utf8').split('\n');
  const escaped = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const commentAbove = (name) => {
    const key = new RegExp(`^\\s*(['"])${escaped(name)}\\1\\s*:`);
    const lines = [];
    for (let i = presetsLines.findIndex((l) => key.test(l)) - 1; i >= 0 && /^\s*\/\//.test(presetsLines[i]); i--) {
      lines.unshift(presetsLines[i].replace(/^\s*\/\/\s?/, ''));
    }
    return lines.join('\n');
  };
  const firstSeen = (name) => {
    const dates = ["'", '"'].map((q) => {
      // A checkout without history (a shallow clone) dates nothing; the page then orders those looks by name alone.
      try {
        const out = execFileSync('git', ['-C', KOMOREBI, 'log', '--reverse', '--format=%aI', `-S${q}${name}${q}:`, '--', 'presets.js', 'komorebi.js'], { encoding: 'utf8' });
        return Date.parse(out.split('\n').find(Boolean) ?? '');
      } catch {
        return NaN;
      }
    }).filter((d) => !Number.isNaN(d));
    return dates.length ? Math.min(...dates) : null;
  };
  // The name the editor's panel gives a parameter, toggles included.
  const labels = Object.fromEntries(Object.entries(PARAMS).filter(([, d]) => d.row?.label).map(([k, d]) => [k, d.row.label]));
  const lineage = JSON.stringify({
    defaults: DEFAULTS,
    ranges: Object.fromEntries([...ranges.values()].map((r) => [r.key, { min: r.min, max: r.max }])),
    angleKeys,
    legacyKeys: LEGACY_KEYS,
    skipKeys: [...FIDELITY_KEYS, ...PLAYBACK_KEYS],
    labels,
    looks: Object.entries(PRESETS).map(([name, params], order) => ({
      name, order, params, comment: commentAbove(name), date: firstSeen(name), experimental: EXPERIMENTAL.includes(name),
      playlists: Object.values(PLAYLISTS).filter((l) => l.items.includes(name)).map((l) => l.name),
    })),
  });
  const lineageFile = `lineage-${createHash('sha256').update(lineage).digest('hex').slice(0, 10)}.json`;
  writeFileSync(join(stage, lineageFile), lineage);

  const bundle = join(tmp, 'komorebi.min.js');
  build({ looks: Object.keys(PRESETS), features: 'all', out: bundle, quiet: true });
  // Named by its content, so a browser holding an older engine never keeps it past a change.
  const file = `komorebi-${createHash('sha256').update(readFileSync(bundle)).digest('hex').slice(0, 10)}.min.js`;
  writeFileSync(join(stage, 'engine.json'), JSON.stringify({ commit, file, lineage: lineageFile }, null, 2) + '\n');

  // Last of all, in this order: the bundle and the lineage land before the engine.json that names them, and older ones go once all have.
  const outDir = join(ROOT, 'public', 'engine');
  const older = readdirSyncOr(outDir).filter((f) => /^komorebi-.*\.min\.js$|^lineage-.*\.json$/.test(f)).map((f) => join(outDir, f));
  install(
    [
      { from: bundle, to: join(outDir, file) },
      { from: join(stage, lineageFile), to: join(outDir, lineageFile) },
      { from: join(stage, 'engine.json'), to: join(outDir, 'engine.json') },
      { from: join(stage, 'engine.ts'), to: join(ROOT, 'src', 'generated', 'engine.ts') },
      { from: join(stage, 'builtins.ts'), to: join(ROOT, 'src', 'generated', 'builtins.ts') },
      { from: join(stage, 'looks.json'), to: join(ROOT, 'test', 'fixtures', 'looks.json') },
      { from: join(stage, lineageFile), to: join(ROOT, 'test', 'fixtures', 'lineage.json') },
    ],
    older,
  );

  console.log(`engine from komorebi ${commit.slice(0, 7)}: ${types.length} params, ${ranges.size} ranges, ${choices.size} select rows, ${Object.keys(LEGACY_KEYS).length} legacy keys, ${Object.keys(PRESETS).length} looks`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
