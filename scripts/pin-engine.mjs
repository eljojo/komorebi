// Pins arboretum to a komorebi commit (spec §7): `node scripts/pin-engine.mjs [commit]`.
// Default commit is komorebi's origin/main as already fetched; this never fetches and never touches
// the komorebi working tree (it reads the repo through `git archive` only).
// Everything is built into a temporary place first and only put where the repo keeps it once every step has
// succeeded (scripts/stage.mjs), so a failed bump leaves the committed files exactly as they were.
// Outputs, all committed so the Worker and the tests never need ~/code/komorebi:
//   src/generated/engine.ts       commit, param types, the editor's slider ranges and select choices, legacy keys,
//                                 look names, experimental look names
//   src/generated/builtins.ts     DEFAULTS' values and every shipped look as the module holds it, so a look that is an
//                                 unchanged built-in can be recognised and refused (builtinTwin in validate.ts)
//   test/fixtures/looks.json      every shipped look, the validator's golden fixtures
//   public/engine/*               the browser bundle (every camera, every feature tier) + engine.json
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { extractRows } from './editor-rows.mjs';
import { install } from './stage.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KOMOREBI = join(homedir(), 'code', 'komorebi');

const commit = execFileSync('git', ['-C', KOMOREBI, 'rev-parse', '--verify', `${process.argv[2] ?? 'origin/main'}^{commit}`], { encoding: 'utf8' }).trim();
const short = commit.slice(0, 7);
const readdirSyncOr = (dir) => { try { return readdirSync(dir); } catch { return []; } };

const tmp = mkdtempSync(join(tmpdir(), 'arboretum-pin-'));
try {
  const archive = execFileSync('git', ['-C', KOMOREBI, 'archive', commit], { maxBuffer: 1 << 30 });
  execFileSync('tar', ['-x', '-C', tmp], { input: archive });

  const { DEFAULTS, LEGACY_KEYS, MAX_LAYERS } = await import(pathToFileURL(join(tmp, 'komorebi-params.js')).href);
  const { PRESETS, EXPERIMENTAL } = await import(pathToFileURL(join(tmp, 'presets.js')).href);
  const { PRESENTATION_PROFILES, FIDELITY_KEYS, PLAYBACK_KEYS } = await import(pathToFileURL(join(tmp,'komorebi-session.js')).href);

  const types = Object.entries(DEFAULTS).map(([k, v]) => {
    if (!['number', 'boolean', 'string'].includes(typeof v)) throw new Error(`DEFAULTS.${k} is a ${typeof v}`);
    return [k, typeof v];
  });

  // The editor's own knobs are the bound on a look (brief 07). editor.js is a DOM module, so its PANEL table is read as text.
  const rows = extractRows(readFileSync(join(tmp, 'editor.js'), 'utf8'), { MAX_LAYERS });
  const editorKeys = ['time_of_day', 'latitude']; // helpers the editor's export carries; DEFAULTS has no entry for them
  const ranges = new Map();
  const choices = new Map();
  for (const row of rows) {
    const type = editorKeys.includes(row.key) ? 'number' : typeof DEFAULTS[row.key];
    if (row.kind === 's') {
      if (type !== 'number') throw new Error(`editor slider ${row.key} is for a ${type} param`);
      if (ranges.has(row.key)) throw new Error(`editor has two sliders for ${row.key}`);
      ranges.set(row.key, row);
    } else {
      if (type !== (row.kind === 'sel' ? 'number' : 'string')) throw new Error(`editor ${row.kind} ${row.key} is for a ${type} param`);
      if (choices.has(row.key)) throw new Error(`editor has two selects for ${row.key}`);
      choices.set(row.key, row.choices);
    }
  }
  const isAngle = (r) => r.key.endsWith('_deg') && ((r.min === -180 && r.max === 180) || (r.min === 0 && r.max === 360));
  const angleKeys = [...ranges.values()].filter(isAngle).map((r) => r.key);
  const integerKeys = [...ranges.values()].filter((r) => r.step === 1).map((r) => r.key);
  const entry = ([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`;
  const stage = join(tmp, 'arboretum-stage');
  mkdirSync(stage);
  writeFileSync(join(stage, 'engine.ts'), [
    '// Generated by scripts/pin-engine.mjs. Do not edit by hand: bump the pin instead.',
    `export const ENGINE_COMMIT = ${JSON.stringify(commit)};`,
    `export const PRESENTATION_IDS: string[] = ${JSON.stringify(Object.keys(PRESENTATION_PROFILES))};`,
    `export const FIDELITY_KEYS: string[] = ${JSON.stringify(FIDELITY_KEYS)};`,
    `export const PLAYBACK_KEYS: string[] = ${JSON.stringify(PLAYBACK_KEYS)};`,
    '',
    'export const PARAM_TYPES: Record<string, \'number\' | \'boolean\' | \'string\'> = {',
    ...types.map(entry),
    '};',
    '',
    '// The komorebi editor\'s slider ranges, exactly as its panel has them (validate.ts adds the leeway).',
    'export const PARAM_RANGES: Record<string, { min: number; max: number }> = {',
    ...[...ranges.values()].map((r) => `  ${JSON.stringify(r.key)}: { "min": ${r.min}, "max": ${r.max} },`),
    '};',
    '',
    '// Sliders whose step is 1: their stretched bounds round to whole numbers.',
    `export const INTEGER_KEYS: string[] = ${JSON.stringify(integerKeys)};`,
    '',
    '// Sliders that are a direction around a circle (-180...180 or 0...360, named *_deg): any number is one.',
    `export const ANGLE_KEYS: string[] = ${JSON.stringify(angleKeys)};`,
    '',
    '// The editor\'s selects: the only values a look may hold for these keys.',
    'export const PARAM_CHOICES: Record<string, (number | string)[]> = {',
    ...[...choices].map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
    '};',
    '',
    '// Old spelling -> current name.',
    'export const LEGACY_KEYS: Record<string, string> = {',
    ...Object.entries(LEGACY_KEYS).map(entry),
    '};',
    '',
    '// Every shipped look, so a `look:<name>` parent can be checked.',
    `export const LOOK_NAMES: string[] = ${JSON.stringify(Object.keys(PRESETS))};`,
    '',
    `export const EXPERIMENTAL_LOOKS: string[] = ${JSON.stringify(EXPERIMENTAL)};`,
    '',
  ].join('\n'));

  const lookBlock = (rec) => Object.entries(rec).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  writeFileSync(join(stage, 'builtins.ts'), [
    '// Generated by scripts/pin-engine.mjs. Do not edit by hand: bump the pin instead.',
    '',
    '// Every key of the engine\'s DEFAULTS and its value: what a look that leaves a key out takes.',
    'export const DEFAULT_VALUES: Record<string, number | boolean | string> = {',
    ...lookBlock(DEFAULTS),
    '};',
    '',
    '// Every shipped look, name -> params, exactly as presets.js holds them.',
    'export const BUILTIN_LOOKS: Record<string, Record<string, number | boolean | string>> = {',
    ...Object.entries(PRESETS).flatMap(([name, look]) => [`  ${JSON.stringify(name)}: {`, ...lookBlock(look).map((l) => `  ${l}`), '  },']),
    '};',
    '',
  ].join('\n'));

  writeFileSync(join(stage, 'looks.json'), JSON.stringify(PRESETS, null, 2) + '\n');

  // embed-build.mjs needs bun; every look name keeps every camera, and `--features all` keeps every fall tier.
  execFileSync('nix', ['shell', 'nixpkgs#bun', '-c', 'node', 'embed-build.mjs', ...Object.keys(PRESETS), '--features', 'all'], { cwd: tmp, stdio: 'inherit' });

  const file = `komorebi-${short}.min.js`;
  writeFileSync(join(stage, 'engine.json'), JSON.stringify({ commit, file }, null, 2) + '\n');

  // Last of all, in this order: the bundle lands before the engine.json that names it, and older bundles go once both have.
  const outDir = join(ROOT, 'public', 'engine');
  const older = readdirSyncOr(outDir).filter((f) => /^komorebi-.*\.min\.js$/.test(f)).map((f) => join(outDir, f));
  install(
    [
      { from: join(tmp, 'dist', 'komorebi.embed.min.js'), to: join(outDir, file) },
      { from: join(stage, 'engine.json'), to: join(outDir, 'engine.json') },
      { from: join(stage, 'engine.ts'), to: join(ROOT, 'src', 'generated', 'engine.ts') },
      { from: join(stage, 'builtins.ts'), to: join(ROOT, 'src', 'generated', 'builtins.ts') },
      { from: join(stage, 'looks.json'), to: join(ROOT, 'test', 'fixtures', 'looks.json') },
    ],
    older,
  );

  console.log(`pinned komorebi ${commit}: ${types.length} params, ${ranges.size} ranges, ${choices.size} select rows, ${Object.keys(LEGACY_KEYS).length} legacy keys, ${Object.keys(PRESETS).length} looks`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
